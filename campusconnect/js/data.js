  function getMatchingStudents(userId, topN = 5) {
    const user = getStudent(userId) || getCurrentUser();
    const others = getStudentsExceptCurrent();
    return others
      .map(s => {
        const commonInterests = s.interests.filter(i => user.interests.includes(i));
        const sameBranch = s.branch === user.branch;
        const sameYear = s.year === user.year;
        const score = commonInterests.length * 3 + (sameBranch ? 2 : 0) + (sameYear ? 1 : 0);
        return { ...s, commonInterests, sameBranch, sameYear, matchScore: score };
      })
      .sort((a, b) => b.matchScore - a.matchScore)
      .slice(0, topN);
  }

